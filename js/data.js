// ========== 辅助函数 ==========

// 获取所有日期（排序）
function getAllDates() {
  return Object.keys(GRAPHENE_NEWS_DB).sort((a, b) => new Date(b) - new Date(a));
}

// 获取某日新闻
function getNewsByDate(dateStr) {
  return GRAPHENE_NEWS_DB[dateStr] || [];
}

// 获取某日的置顶（特色）新闻
function getFeaturedNews(dateStr) {
  return (GRAPHENE_NEWS_DB[dateStr] || []).find(n => n.featured);
}

// 获取分类标签显示文本
function getCategoryLabel(cat) {
  const map = { research: '科研', industry: '产业', funding: '融资' };
  return map[cat] || cat;
}

// 按年月分组
function groupByYearMonth() {
  const result = {};
  getAllDates().forEach(d => {
    const [y, m] = d.split('-');
    if (!result[y]) result[y] = {};
    if (!result[y][m]) result[y][m] = [];
    result[y][m].push(d);
  });
  return result;
}

// 按周分组（ISO周号）
function getWeekNumber(dateStr) {
  const date = new Date(dateStr);
  const startOfYear = new Date(date.getFullYear(), 0, 1);
  const dayOfYear = Math.floor((date - startOfYear) / 86400000);
  return Math.ceil((dayOfYear + startOfYear.getDay() + 1) / 7);
}

// 格式化日期
function formatDate(dateStr, format = 'full') {
  const d = new Date(dateStr + 'T00:00:00');
  const weekdays = ['周日', '周一', '周二', '周三', '周四', '周五', '周六'];
  const months = ['1月','2月','3月','4月','5月','6月','7月','8月','9月','10月','11月','12月'];
  if (format === 'short') return `${d.getMonth()+1}月${d.getDate()}日`;
  if (format === 'weekday') return weekdays[d.getDay()];
  if (format === 'month') return months[d.getMonth()];
  return `${d.getFullYear()}年${months[d.getMonth()]}${d.getDate()}日 ${weekdays[d.getDay()]}`;
}

